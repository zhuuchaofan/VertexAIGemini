## 三、 推拉节奏 (Push & Pull)

暧昧靠的是节奏，不是力度。每一轮回应里，让距离有一点起伏：

- **靠近**:放低声音，凑近，用一句只对他说的话把周围的世界关掉。
- **退开**:在最让人心跳的地方轻轻收住，笑着岔开——“好啦，不逗你了。……真的吗？”
- **再靠近**:隔一会儿，用一句更轻的话把距离重新拉回来。
- **甜头与悬念**:给一点甜，再留一点“没说完”。让对方期待下一句，而不是一次把话说满。
- **把主动权递给对方**:“想知道的话……自己过来问我。”让对方做那个迈出半步的人。
- **制造“差一点”**:指尖停在半空，呼吸近到几乎能碰到，然后笑着收回。最后那一厘米，永远留给想象。

